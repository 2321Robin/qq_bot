def build_help_text(ai_prefix: str, *, roco_enabled: bool = True) -> str:
    lines = [
        "可用功能：",
        "",
        "基础命令：",
        "/help 或 /帮助 - 查看这份帮助",
        "/version 或 /版本 - 查看当前机器人版本",
        "",
        "AI 问答：",
        f"{ai_prefix} <问题> - 直接提问，如「{ai_prefix} 今天玩什么」",
        "@机器人 <问题> - 点名提问，可发图、引用消息追问",
        "",
        "早晚报：",
        "/早报 - 手动触发生活早报",
        "/晚报 - 手动触发生活晚报",
        "/AI早报 - 最新一期 AI 日报（每天 10:00 定时发送）",
        "",
        "个人记忆（只影响自己）：",
        "/记忆保存 <内容> - 让机器人记住你的偏好（≤200 字）",
        "/记忆查看 - 查看机器人记住你的内容",
        "/记忆删除 <编号> / /记忆删除 全部 - 删除指定或全部记忆",
        "/记忆关闭 - 清空并停用对你的长期记忆",
    ]
    if roco_enabled:
        lines += [
            "",
            "洛克查询：",
            "/精灵 迪莫 - 查询洛克王国世界精灵图鉴、属性、种族值和进化条件",
            "/洛克 迪莫 - /精灵 的别名，效果相同",
            "/技能 闪光 - 查询技能效果、类型、威力、PP 和可用精灵",
            "@机器人 迪莫 - 直接查询精灵；@机器人 闪光 - 直接查询技能",
        ]
    lines += [
        "",
        "管理员命令：",
        "/表达学习 - 触发一轮表达/黑话/观察卡学习",
        "/表达 列表 | /表达 禁用 <编号> - 管理表达模板池",
        "/黑话 列表 | /黑话 修正 <词> <释义> | /黑话 禁用 <词> - 管理黑话词库",
        "/配额 - 查询 AI 配额使用情况",
        "/最近故障 - 近期错误摘要",
    ]
    return "\n".join(lines)
